"""Generate the [data-icon=<key>] block of apps/client/src/gameplay-panels.css from the pack icon atlases.
Run from repo root: python3 packages/assets/pack/vehicle_items/src/gen_icon_css.py  (rewrites between the ICONS markers)."""
import json, os
R = 'packages/assets/pack/'
SRC = [('manifest.json', {'items', 'equipment'}), ('items/manifest.items.json', {'items_icons', 'items_skills', 'items_skill_tabs', 'items_xp', 'items_pets', 'items_build', 'items_missing', 'items_temp'}), ('vehicle_items/manifest.vehicle_items.json', {'vitems_icons'}), ('nature/manifest.nature.json', {'nature_roadicons', 'nature_toolicons', 'nature_adr128', 'nature_icons'})]
rel = '../../../packages/assets/pack/'
ALIAS = {'icon_xp': ['xp'], 'icon_temp': ['temp'], 'icon_temp_hot': ['temp_hot'], 'icon_temp_cold': ['temp_cold']}  # ADR-135: the XP toast uses data-icon="xp" (gather-fx ToastStack.addXp)
UI_OK = {'items_skills', 'items_skill_tabs', 'items_xp', 'items_build', 'items_temp'}  # ui-category atlases emitted too (ADR-113 skill icons, ADR-132 tab icons, ADR-224 build piece icons, seasons HUD temperature gauge items_temp)
out, keys, seen = [], {}, set()
for f, atl in SRC:
    m = json.load(open(R + f)); base = os.path.dirname(f)
    A = {a['key']: a for a in m['atlases']}
    for ak in sorted(atl):
        a = A[ak]; img = rel + os.path.join(base, a['image']).lstrip('/')
        p2 = a.get('pages') or []
        src = f'image-set(url("{img}") 1x, url("{rel + os.path.join(base, p2[0]["image"])}") 2x)' if p2 else f'url("{img}")'
        ks = []
        for s in m['sprites']:
            if s.get('atlas') != ak or (s['category'] not in ('item', 'equipment') and not (ak in UI_OK and s['category'] == 'ui')) or s['key'] in seen: continue
            seen.add(s['key']); fr = s['animations']['idle']['frames'][0]; c, r = fr % a['columns'], fr // a['columns']
            px = 0 if a['columns'] == 1 else c * 100 / (a['columns'] - 1); py = 0 if a['rows'] == 1 else r * 100 / (a['rows'] - 1)
            for k2 in [s['key']] + ALIAS.get(s['key'], []): ks.append(k2); out.append(f'[data-icon="{k2}"]{{--cz-ipos:{px:.4g}% {py:.4g}%}}')
        if ks:
            sel = ','.join(f'[data-icon="{k}"]' for k in ks)
            out.insert(len(out) - len(ks), f'{sel}{{--cz-icon:{src};--cz-isize:{a["columns"] * 100}% {a["rows"] * 100}%}}')
            keys[ak] = len(ks)
css = 'apps/client/src/gameplay-panels.css'
s = open(css).read(); a0 = '/* ICONS:BEGIN'; a1 = '/* ICONS:END */'
i, j = s.index(a0), s.index(a1)
hdr = f'/* ICONS:BEGIN generated by packages/assets/pack/vehicle_items/src/gen_icon_css.py ({len(seen)} keys: {keys}) */\n'
open(css, 'w').write(s[:i] + hdr + '\n'.join(out) + '\n' + s[j:])
print(len(seen), keys)
