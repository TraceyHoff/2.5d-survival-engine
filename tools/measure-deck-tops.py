#!/usr/bin/env python3
"""ADR-197: derive each deck (layer-0 building) sprite's top-face height from its art.

The top face's back corner is the first opaque row of the r0 frame. Its height above the ground is
pivot_y - top_row - (fw + fh) / 2 * tileH/2. Writes packages/render/src/building/deckTops.generated.ts.
Re-run after Art changes a deck sprite: python3 tools/measure-deck-tops.py
"""
import json, os
from PIL import Image
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(f"{R}/assets/manifest.json")); sprites = man["sprites"]
items = sprites.items() if isinstance(sprites, dict) else [(s["key"], s) for s in sprites]
HH = 16; out = {}; atl = {}
for key, s in sorted(items):
    b = s.get("building")
    if not b or b.get("layer") != 0 or key.startswith("roof"): continue  # roofs are never decks
    a = s["atlas"]
    if a not in atl:
        p = f"{R}/assets/atlases/{a}"
        if not os.path.exists(p + ".png"): continue
        atl[a] = (json.load(open(p + ".json"))["frames"], Image.open(p + ".png").convert("RGBA"))
    frames, img = atl[a]
    names = sorted(frames)  # frame index order
    byidx = {f.get("index", i): (n, f) for i, (n, f) in enumerate((n, frames[n]) for n in frames)}
    fi = b["frames"][0][0]
    if fi not in byidx: continue
    _, f = byidx[fi]; fr = f["frame"]
    c = img.crop((fr["x"], fr["y"], fr["x"] + fr["w"], fr["y"] + fr["h"])).getchannel("A").point(lambda v: 255 if v > 20 else 0)
    bb = c.getbbox()
    if not bb: continue
    piv = f.get("pivot", s["anchor"])["y"] * fr["h"]
    fw, fh = b["footprint"]["w"], b["footprint"]["h"]
    top = piv - bb[1] - (fw + fh) / 2 * HH
    if top < 0 or top > 40: continue  # not a slab (roofs, ramps): no deck culling
    out[key] = round(top)
src = "/** ADR-197: generated by tools/measure-deck-tops.py from the deck sprites' art (top-face height above the ground, px). Do not edit. */\n"
src += "export const DECK_TOP_PX: Readonly<Record<string, number>> = {\n" + "".join(f"  {json.dumps(k)}: {v},\n" for k, v in out.items()) + "};\n"
open(f"{R}/packages/render/src/building/deckTops.generated.ts", "w").write(src)
print(len(out), out)
