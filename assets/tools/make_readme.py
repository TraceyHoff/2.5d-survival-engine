"""Generates README.md (file inventory with dims, pivots, frames, fps) from manifest.json."""
import os, json, glob
from PIL import Image
from atlas import ROOT
M = json.load(open(os.path.join(ROOT, "manifest.json")))
A = {a["key"]: a for a in M["atlases"]}
L = []
w = L.append
w("# Cozy-Wild Starter Pack (wave 1)\n")
w("This is the canonical shared asset folder. Art direction is in [STYLE_GUIDE.md](STYLE_GUIDE.md). Engine wiring is in [INTEGRATION.md](INTEGRATION.md).")
w("Everything here is generated by `python3 tools/build_all.py && python3 tools/audio.py && python3 tools/build_all.py && python3 tools/preview.py && python3 tools/make_readme.py`")
w("(python3, Pillow 12, numpy 2, ffmpeg with libvorbis). The output is deterministic.\n")
w("Quick look: `preview.png` (= `preview/preview.png`, 2x: `preview/preview_2x.png`), `preview/scene.gif`, `preview/player_walk.gif`, `preview/water.gif`, and `preview/contact_<atlas>.png`.\n")
w("## Conventions (summary)")
w("- 2:1 iso, tile 64×32, `zStep` 16 px. All PNGs are RGBA8 with straight (non-premultiplied) alpha.")
w("- Atlases are **uniform grids**, the engine manifest v1 format (`frameW/frameH/columns/rows`). The frame index runs row-major. Direction rows are offset by `dirStride` = `columns`.")
w("- **Pivot/anchor** is normalized `(x, y)` within the frame. Characters use the feet, props use the base center, tiles use the diamond center, buildings use the footprint center on the ground, and icons/FX use the frame center.")
w("- 8-direction row order is `round(facing/45°)` with `facing 0 = +x`. On screen that is: 0 down-right, 1 down, 2 down-left, 3 left, 4 up-left, 5 up, 6 up-right, 7 right.")
w("  4-direction order: 0 down-right, 1 down-left, 2 up-left, 3 up-right.")
w("- Each `atlases/<key>.json` next to the PNG is TexturePacker-hash compatible, with frame names and pivots. Individual frames are in `sprites/<category>/<key>/`.")
w("- Characters and zombies have **no baked shadow** (renderer shadow, or `fx_shadow_blob`). Static props carry a soft 30% plum contact shadow.")
w("- Trees, bushes and grass have **no sway frames**. Their sprite entries carry `sway: {amp (px), freq (Hz), stiffness (0..1)}` for the renderer's vertex-shader wind.\n")
w("## Atlases\n")
w("| atlas | image | frame | grid | sheet px | emissive | category |")
w("|---|---|---|---|---|---|---|")
for a in M["atlases"]:
    cats = sorted({s["category"] for s in M["sprites"] if s["atlas"] == a["key"]})
    w(f"| `{a['key']}` | `{a['image']}` | {a['frameW']}×{a['frameH']} | {a['columns']}×{a['rows']} | {a['frameW']*a['columns']}×{a['frameH']*a['rows']} | {'yes' if a.get('emissive') else '-'} | {', '.join(cats)} |")
w("\n## Sprites\n")
w("Frames are listed as `anim: frames @fps (dirs, loop)`. The pivot is in pixels within the frame.\n")
cur = None
for s in sorted(M["sprites"], key=lambda s: (s["category"], s["atlas"], s["key"])):
    if s["category"] != cur:
        cur = s["category"]; w(f"\n### {cur}\n"); w("| key | atlas | pivot px (norm) | animations | extra |"); w("|---|---|---|---|---|")
    a = A[s["atlas"]]; px = (round(s["anchor"]["x"] * a["frameW"], 1), round(s["anchor"]["y"] * a["frameH"], 1))
    an = "; ".join(f"{k}: {v['frames'][0]}..{v['frames'][-1]} ({len(v['frames'])}f) @{v['fps']}" + (f" ×{v.get('directions',1)}dir" if v.get('directions', 1) > 1 else "") + ("" if v.get("loop", True) else " once") for k, v in s["animations"].items())
    ex = []
    if "building" in s:
        b = s["building"]; ex.append(f"piece `{b['piece']}` {b['footprint']['w']}×{b['footprint']['h']} L{b['layer']} rotArt `{s.get('rotationArt')}` rots {len(b['frames'])}×4 dmg")
    if "sway" in s: ex.append(f"sway {s['sway']}")
    w(f"| `{s['key']}` | {s['atlas']} | {px} ({s['anchor']['x']}, {s['anchor']['y']}) | {an} | {'; '.join(ex)} |")
w("\n## Sounds (`audio/`, 44.1 kHz mono, OGG Vorbis q5 + WAV masters)\n")
w("| key | category | files | volume | pitchJitter | loop | duration |"); w("|---|---|---|---|---|---|---|")
import wave
for s in M["sounds"]:
    durs = []
    for f in s["files"]:
        wv = os.path.join(ROOT, f.rsplit(".", 1)[0] + ".wav")
        with wave.open(wv) as h: durs.append(h.getnframes() / h.getframerate())
    w(f"| `{s['key']}` | {s['category']} | {', '.join('`'+f+'`' for f in s['files'])} | {s['volume']} | {s['pitchJitter']} | {s['loop']} | {min(durs):.2f}–{max(durs):.2f}s |")
w("\n## VFX definitions\n")
w("| key | sprite | lifetime | blend | particles |"); w("|---|---|---|---|---|")
for v in M["vfx"]: w(f"| `{v['key']}` | `{v['sprite']}` | {v['lifetime']} | {v.get('blend','normal')} | {json.dumps(v.get('particles')) if v.get('particles') else '-'} |")
w("\n## Tints / palettes / variants\n")
for t in M["tintSets"]: w(f"- tintSet `{t['key']}`: {', '.join(t['tints'])}")
for p in M["palettes"]: w(f"- palette `{p['key']}`: {p['source']} → {p['target']}")
for vs in M["variantSets"]: w(f"- variantSet `{vs['key']}` (base `{vs['base']}`): " + ", ".join(f"`{v['key']}`" + (f" sprite={v['sprite']}" if 'sprite' in v else '') + (f" tint={v['tint']}[{v.get('tintIndex',0)}]" if 'tint' in v else '') + (f" palette={v['palette']}" if 'palette' in v else '') for v in vs["variants"]))
w("\n## Other files\n")
w("- `manifest.json`: the engine manifest v1 (atlases, sprites, sounds, vfx, tintSets, palettes, variantSets). It adds the extra fields `rotationArt` and `sway`.")
w("- `ids.lock.json`: namespaced stable id lock. It is seeded from `engine/packages/assets/sample/ids.lock.json`, so every pre-existing key keeps its id.")
w("- `palette.json` / `palette.png`: palette ramps. `STYLE_GUIDE.md`: art direction.")
w("- `audio/manifest.json`: the sound list (merged into `manifest.json`).")
w("- `preview/`: `preview.png` and `preview_2x.png` (scene), `scene.gif`, `early_concept.png`, `contact_<atlas>.png`, `player_walk.gif`, `player_variants_actions.gif`,")
w("  `zombies_walk.gif`, `zombies_attack_death.gif`, `water.gif`, `campfire_torch.gif`, `bunny.gif`, `fx.gif`.")
w("- `tools/`: generators (`palette.py`, `toon.py` toon renderer, `iso.py` iso box renderer, `chars.py`, `critters.py`, `nature.py`, `terrain.py`, `buildings.py`,")
w("  `items.py`, `fx.py`, `audio.py`, `atlas.py`, `build_all.py`, `preview.py`, `make_readme.py`).")
w(f"\nTotals: {len(M['atlases'])} atlases, {len(M['sprites'])} sprites, {len(M['sounds'])} sounds, {len(M['vfx'])} vfx, {len(glob.glob(os.path.join(ROOT,'sprites','**','*.png'), recursive=True))} individual frame PNGs.")
open(os.path.join(ROOT, "README.md"), "w").write("\n".join(L) + "\n")
print("README ok")
